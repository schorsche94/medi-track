create table medication_categories (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    name varchar(120) not null unique,
    description varchar(255)
);

create table medication_forms (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    name varchar(120) not null unique,
    description varchar(255)
);

create table users (
    chat_id bigint not null,
    first_name varchar(255),
    last_name varchar(255),
    registered_at timestamp(6) not null,
    username varchar(255),
    primary key (chat_id)
);

create table medications (
    id bigint generated by default as identity primary key,
    active_substance varchar(255),
    dosage varchar(255),
    instructions varchar(255),
    name varchar(255),
    description varchar(255),
    form_id bigint,
    category_id bigint,
    added_by bigint,
    constraint fk_medications_form foreign key (form_id) references medication_forms (id),
    constraint fk_medications_category foreign key (category_id) references medication_categories (id),
    constraint fk_medications_user foreign key (added_by) references users (chat_id)
);

create table schedules (
    id bigint generated by default as identity primary key,
    custom_instruction varchar(255),
    duration_days integer,
    end_date date,
    frequency_per_day integer,
    intake_instruction varchar(255) check ((intake_instruction in ('AFTER_MEAL','BEFORE_MEAL','WITH_WATER','WITH_FOOD','ON_EMPTY_STOMACH','AT_BEDTIME','IN_THE_MORNING','AVOID_ALCOHOL','AVOID_DAIRY','OTHER'))),
    interval_days integer,
    pause_days integer,
    scheduled_times jsonb,
    start_date date,
    status varchar(255) check ((status in ('ACTIVE','PAUSED','COMPLETED','CANCELLED'))),
    medicine_id bigint not null,
    added_by bigint,
    constraint fk_schedules_medicine foreign key (medicine_id) references medications (id),
    constraint fk_schedules_user foreign key (added_by) references users (chat_id)
);
